import pandas as pd
import streamlit as st
from model import train_model, estimate_price

st.set_page_config(
    page_title="Vehicle Value Intelligence",
    page_icon="🚗",
    layout="wide",
    initial_sidebar_state="expanded",
)

st.markdown("""
<style>
    .block-container {padding-top: 2rem; padding-bottom: 3rem; max-width: 1180px;}
    .hero {padding: 1.5rem 1.7rem; border: 1px solid rgba(128,128,128,.25);
           border-radius: 18px; margin-bottom: 1.2rem;}
    .eyebrow {font-size: .75rem; letter-spacing: .16em; font-weight: 700; opacity: .7;}
    .muted {opacity: .72; font-size: .92rem;}
    div[data-testid="stMetric"] {border: 1px solid rgba(128,128,128,.22);
        border-radius: 14px; padding: 14px 16px;}
</style>
""", unsafe_allow_html=True)

@st.cache_resource
def get_model_and_data():
    return train_model()

model, data = get_model_and_data()

st.markdown(
    '<div class="hero"><div class="eyebrow">DATA SCIENCE PROJECT · INDIA</div>'
    '<h1>Vehicle Value Intelligence</h1>'
    '<p class="muted">Explore a transparent machine-learning workflow for estimating used-car values.</p></div>',
    unsafe_allow_html=True,
)

with st.sidebar:
    st.markdown("### Project controls")
    st.caption("Choose vehicle attributes and run an estimate.")
    st.divider()
    st.markdown("**Model**")
    st.write("Ridge regression")
    st.write("Standard scaling + one-hot encoding")
    st.markdown("**Dataset**")
    st.write(f"{len(data)} illustrative records")
    st.caption("This demo is educational—not a live market valuation.")

overview, estimator, explorer = st.tabs(["Overview", "Price estimator", "Dataset explorer"])

with overview:
    a, b, c, d = st.columns(4)
    a.metric("Sample records", f"{len(data):,}")
    b.metric("Brands", f"{data['brand'].nunique()}")
    c.metric("Fuel types", f"{data['fuel'].nunique()}")
    d.metric("Median sample price", f"₹{data['price_lakh'].median():.2f} L")
    st.subheader("What the model learns from")
    st.write("The pipeline combines numeric vehicle attributes with encoded categories, then fits a Ridge regression model.")
    left, right = st.columns(2)
    with left:
        st.markdown("**Numeric features**")
        st.write("Model year · Kilometers driven · Engine capacity · Previous owners")
    with right:
        st.markdown("**Categorical features**")
        st.write("Brand · Fuel · Transmission")
    st.subheader("Sample price distribution")
    st.bar_chart(data.groupby("brand", as_index=True)["price_lakh"].median())
    st.caption("Bars show median prices in the illustrative dataset, not current market averages.")

with estimator:
    st.subheader("Estimate a vehicle's value")
    st.write("Set the vehicle details below. The estimate is generated by the trained preprocessing and regression pipeline.")
    with st.form("estimate_form"):
        left, right = st.columns(2)
        with left:
            brand = st.selectbox("Brand", sorted(data.brand.unique()))
            year = st.slider("Model year", int(data.year.min()), int(data.year.max()), 2020)
            km = st.number_input("Kilometers driven", 0, 300000, 45000, step=5000)
            engine = st.selectbox("Engine capacity (cc)", sorted(data.engine_cc.unique()), index=2)
        with right:
            fuel = st.selectbox("Fuel", sorted(data.fuel.unique()))
            transmission = st.selectbox("Transmission", sorted(data.transmission.unique()))
            owners = st.selectbox("Previous owners", [1, 2, 3, 4], index=0)
        submitted = st.form_submit_button("Calculate estimate", type="primary", use_container_width=True)

    if submitted:
        price, _ = estimate_price(year, km, engine, owners, brand, fuel, transmission)
        st.success("Estimate generated")
        x, y = st.columns([1, 2])
        with x:
            st.metric("Estimated value", f"₹{price:.2f} lakh")
        with y:
            st.info("Treat this as a learning demo only. The small synthetic-style sample is not representative of all Indian used-car listings, and the model has not been validated for buying or selling decisions.")
        st.markdown("**Your selected vehicle**")
        st.write(f"{year} {brand} · {fuel} · {transmission} · {engine} cc · {km:,} km · {owners} previous owner(s)")

with explorer:
    st.subheader("Explore the training dataset")
    f1, f2 = st.columns(2)
    with f1:
        selected_brand = st.multiselect("Filter by brand", sorted(data.brand.unique()), default=sorted(data.brand.unique()))
    with f2:
        selected_fuel = st.multiselect("Filter by fuel", sorted(data.fuel.unique()), default=sorted(data.fuel.unique()))
    filtered = data[data.brand.isin(selected_brand) & data.fuel.isin(selected_fuel)]
    st.caption(f"Showing {len(filtered)} of {len(data)} records")
    st.dataframe(filtered, use_container_width=True, hide_index=True)
    if not filtered.empty:
        st.subheader("Mileage vs listed sample price")
        st.scatter_chart(filtered, x="km_driven", y="price_lakh", color="brand")
    else:
        st.warning("No records match those filters. Select at least one brand and fuel type.")

st.divider()
st.caption("Built with Python · pandas · scikit-learn · Streamlit | Model: Ridge regression | Dataset: small illustrative sample")
